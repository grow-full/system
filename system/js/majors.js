// 학과 이름에서 과목 이름이 어색해지는 곳만 따로 정한다
const MAJOR_SUBJECTS = {
  '수의예과': '수의학', '의예과': '의학',
  '인문학자율전공학부': '인문학', '경영학자율전공학부': '경영학', '자율전공학부': '융합학문',
};

function collegeOf(dept) {
  return COLLEGES.find((c) => c.depts.includes(dept)) || null;
}

function isMajor(dept) {
  return Boolean(collegeOf(dept));
}

// '국어국문학과' → '국어국문학', '기계공학부' → '기계공학', '국어교육과' → '국어교육학'
function majorSubject(dept) {
  if (MAJOR_SUBJECTS[dept]) return MAJOR_SUBJECTS[dept];
  const stem = dept.replace(/(과|부)$/, '');
  return stem.endsWith('학') ? stem : `${stem}학`;
}
